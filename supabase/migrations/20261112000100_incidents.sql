-- ============================================================================
-- 0007 — Incidencias del local
--
-- Cada incidencia la declara un único usuario (relación 1:N: un usuario puede
-- tener muchas incidencias) y pertenece a una planta. La categoría describe el
-- tipo de avería o aviso: electrodoméstico, electricidad, fontanería, mobiliario,
-- limpieza, falta de stock u otro.
--
-- La lectura está abierta a todo el equipo; la escritura va siempre por RPC para
-- fijar el autor y evitar que un empleado cambie incidencias ajenas o el estado.
-- ============================================================================

create table if not exists public.incident (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  floor text not null
    check (floor in ('planta_baja', 'karaoke', 'terraza')),
  category text not null
    check (category in (
      'electrodomestico', 'electricidad', 'fontaneria',
      'mobiliario', 'limpieza', 'stock', 'otro'
    )),
  title text not null check (length(btrim(title)) between 1 and 120),
  description text not null default '',
  status text not null default 'abierta'
    check (status in ('abierta', 'en_proceso', 'resuelta')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists idx_incident_user
  on public.incident(user_id);
create index if not exists idx_incident_floor
  on public.incident(floor);
create index if not exists idx_incident_status
  on public.incident(status);
create index if not exists idx_incident_created
  on public.incident(created_at desc);

-- Autor ya resuelto para pintar el listado sin consultas adicionales.
create or replace view public.incident_view
with (security_invoker = true) as
select
  i.id,
  i.user_id,
  p.name as user_name,
  p.surname as user_surname,
  i.floor,
  i.category,
  i.title,
  i.description,
  i.status,
  i.created_at,
  i.updated_at,
  i.resolved_at
from public.incident i
join public.profiles p on p.id = i.user_id;

-- ---------------------------------------------------------------------------
-- updated_at automático
-- ---------------------------------------------------------------------------

drop trigger if exists trg_incident_touch on public.incident;
create trigger trg_incident_touch
before update on public.incident
for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Grants y RLS
--
-- Solo lectura directa: las altas, ediciones y borrados pasan por las RPC para
-- validar autoría y estado. El rol anon no recibe nada.
-- ---------------------------------------------------------------------------

revoke all on table public.incident from public, anon;
revoke insert, update, delete on table public.incident from authenticated;
grant select on table public.incident to authenticated;
grant select on table public.incident_view to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.incident enable row level security;

drop policy if exists incident_read on public.incident;
create policy incident_read on public.incident
  for select to authenticated using (true);

-- ---------------------------------------------------------------------------
-- Alta y edición de una incidencia
-- ---------------------------------------------------------------------------

create or replace function public.save_incident(
  p_id bigint,
  p_floor text,
  p_category text,
  p_title text,
  p_description text,
  p_status text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id bigint := public.current_profile_id();
  v_owner bigint;
  v_status text;
  v_id bigint;
begin
  if v_profile_id is null then
    raise exception 'Sesión no válida o cuenta desactivada';
  end if;
  if coalesce(btrim(p_title), '') = '' then
    raise exception 'El título es obligatorio';
  end if;
  if p_floor not in ('planta_baja', 'karaoke', 'terraza') then
    raise exception 'La planta no es válida';
  end if;
  if p_category not in (
    'electrodomestico', 'electricidad', 'fontaneria',
    'mobiliario', 'limpieza', 'stock', 'otro'
  ) then
    raise exception 'La categoría no es válida';
  end if;

  if p_id is null then
    -- El autor siempre es quien declara la incidencia.
    insert into public.incident (
      user_id, floor, category, title, description, status
    )
    values (
      v_profile_id,
      p_floor,
      p_category,
      left(btrim(p_title), 120),
      left(coalesce(btrim(p_description), ''), 2000),
      'abierta'
    )
    returning id into v_id;
    return v_id;
  end if;

  select user_id, status into v_owner, v_status
    from public.incident
   where id = p_id
   for update;

  if v_owner is null then
    raise exception 'Incidencia no encontrada';
  end if;

  if public.is_admin() then
    v_status := coalesce(nullif(btrim(p_status), ''), v_status);
    if v_status not in ('abierta', 'en_proceso', 'resuelta') then
      raise exception 'El estado no es válido';
    end if;
  else
    if v_owner <> v_profile_id then
      raise exception 'Solo puedes editar tus propias incidencias';
    end if;
    if v_status <> 'abierta' then
      raise exception 'Solo se pueden editar las incidencias abiertas';
    end if;
  end if;

  update public.incident set
    floor = p_floor,
    category = p_category,
    title = left(btrim(p_title), 120),
    description = left(coalesce(btrim(p_description), ''), 2000),
    status = v_status,
    resolved_at = case
      when v_status = 'resuelta' then coalesce(resolved_at, now())
      else null
    end
  where id = p_id
  returning id into v_id;

  return v_id;
end $$;

-- ---------------------------------------------------------------------------
-- Borrado de una incidencia
-- ---------------------------------------------------------------------------

create or replace function public.delete_incident(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id bigint := public.current_profile_id();
  v_owner bigint;
  v_status text;
begin
  if v_profile_id is null then
    raise exception 'Sesión no válida o cuenta desactivada';
  end if;

  select user_id, status into v_owner, v_status
    from public.incident
   where id = p_id
   for update;

  if v_owner is null then
    raise exception 'Incidencia no encontrada';
  end if;

  if not public.is_admin() then
    if v_owner <> v_profile_id then
      raise exception 'Solo puedes borrar tus propias incidencias';
    end if;
    if v_status <> 'abierta' then
      raise exception 'Solo se pueden borrar las incidencias abiertas';
    end if;
  end if;

  delete from public.incident where id = p_id;
end $$;

-- ---------------------------------------------------------------------------
-- Permisos de ejecución
